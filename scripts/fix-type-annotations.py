# Merge all types
ALL_FUNC_TYPES = {**HANDLER_TYPES, **SERVE_TYPES, **OTHER_FUNC_TYPES, **CALLBACK_TYPES}


def annotate_function(line: str, func_name: str, types: list[str]) -> str:
    """Add type annotations to a function signature."""
    if not types:
        return line
    
    # Match: (params) => { or (params) {
    arrow_match = re.match(
        r'^(\s*)(async\s+)?(?:const\s+)?function\s+' + re.escape(func_name) + r'\s*\((.+?)\)\s*(?:=>\s*)?\{',
        line
    )
    if not arrow_match:
        return line
    
    indent = arrow_match.group(1)
    is_async = 'async ' if arrow_match.group(2) else ''
    is_const = 'const ' if 'const ' in line else ''
    params_str = arrow_match.group(3)
    
    # Split params
    params = params_str.split(',')
    annotated_params = []
    for i, p in enumerate(params):
        p = p.strip()
        if not p:
            annotated_params.append(p)
            continue
        if '=' in p:
            base, default = p.split('=', 1)
            base = base.strip()
            default = default.strip()
        else:
            base = p
            default = ''
        
        if i < len(types):
            annotated_params.append(f"{base}: {types[i]}{' = ' + default if default else ''}")
        else:
            annotated_params.append(p)
    
    # Determine return type for handler functions
    ret_type = ''
    if func_name.startswith('handle') or func_name.startswith('serve'):
        ret_type = ': Response'
    
    # Build new signature
    ret = f"{ret_type}"
    new_line = f"{indent}{is_async}{is_const}function {func_name}({', '.join(annotated_params)}){ret} {{"
    
    return new_line


def process_file(filepath: str) -> int:
    """Process a file and return the number of annotations applied."""
    with open(filepath, 'r', encoding='utf-8') as f:
        lines = f.readlines()
    
    count = 0
    new_lines = []
    
    for line in lines:
        # Match function declarations with parameters
        match = re.match(
            r'^(\s*)(async\s+)?(?:const\s+)?function\s+(\w+)\s*\((.+?)\)\s*(?:=>\s*)?\{',
            line
        )
        if not match:
            new_lines.append(line)
            continue
        
        func_name = match.group(3)
        if func_name in ALL_FUNC_TYPES:
            new_line = annotate_function(line, func_name, ALL_FUNC_TYPES[func_name])
            if new_line != line:
                count += 1
            new_lines.append(new_line)
        else:
            new_lines.append(line)
    
    with open(filepath, 'w', encoding='utf-8') as f:
        f.writelines(new_lines)
    
    return count


